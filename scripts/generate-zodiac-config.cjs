'use strict';
// Generated PHP is a deployment projection; the catalog JSON remains authoritative.
const fs = require('node:fs');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const files = ['docs/contracts/rules/zodiac-rules.json', 'docs/contracts/product-scope.json', 'docs/contracts/rules/category-weights.json'];
const input = files.map(p => fs.readFileSync(p, 'utf8'));
const [catalog, scope, categories] = input.map(JSON.parse);
function php(x, depth = 0) {
  if (x === null) return 'null';
  if (typeof x === 'boolean') return String(x);
  // Decimal values stay strings all the way into the exact arithmetic layer.
  if (typeof x !== 'object') return "'" + String(x).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
  const rows = Object.entries(x).map(([k, v]) => '    '.repeat(depth + 1) + (Array.isArray(x) ? '' : php(k) + ' => ') + php(v, depth + 1) + ',');
  return '[\n' + rows.join('\n') + '\n' + '    '.repeat(depth) + ']';
}
const hash = crypto.createHash('sha256').update(JSON.stringify({catalog, scope, categories})).digest('hex');
const output = `<?php\ndeclare(strict_types=1);\n\n// GENERATED by scripts/generate-zodiac-config.cjs. Do not edit.\n// Input SHA-256: ${hash}\nreturn ${php({catalog, scope, categoryWeights: categories.weights})};\n`;
const target = 'wp-content/plugins/love-fortune-core/config/zodiac.php';
if (process.argv.includes('--check')) assert.equal(fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n'), output, 'Stale Zodiac runtime projection');
else fs.writeFileSync(target, output);
console.log('Zodiac projection: PASS');
